  /**
   * 伴奏长度对齐：把 bass 的总拍数补齐/裁齐到与旋律一致。
   * 多出来的拍并到最后一个音（长音收束），不足时延长最后一个音。
   * 这样左手/双手跟练不会被“伴奏先结束”打断。
   */
  function normalizeBass(song) {
    if (!song || !song.bass || !song.bass.length) return song;
    var melBeats = 0, i;
    for (i = 0; i < song.notes.length; i++) melBeats += song.notes[i][1];
    var bassBeats = 0;
    for (i = 0; i < song.bass.length; i++) bassBeats += song.bass[i][1];
    if (Math.abs(melBeats - bassBeats) < 0.01) return song;
    var bass = song.bass.slice();
    if (bassBeats < melBeats) {
      bass[bass.length - 1] = [bass[bass.length - 1][0], bass[bass.length - 1][1] + (melBeats - bassBeats)];
    } else {
      while (bass.length > 1 && bassBeats - bass[bass.length - 1][1] >= melBeats - 0.001) {
        bassBeats -= bass[bass.length - 1][1];
        bass.pop();
      }
      bass[bass.length - 1] = [bass[bass.length - 1][0], melBeats - (bassBeats - bass[bass.length - 1][1])];
    }
    song.bass = bass;
    return song;
  }
